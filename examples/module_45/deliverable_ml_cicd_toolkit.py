class WorkflowGenerator:
    """Generates GitHub Actions workflows for ML projects."""

    def __init__(self):
        """Initialize the generator."""
        pass

    def generate(self, config: WorkflowConfig) -> str:
        """Generate a complete workflow YAML."""
        sections = [
            self._generate_header(config),
            self._generate_triggers(config),
            self._generate_env(config),
            self._generate_jobs(config),
        ]
        return "\n".join(sections)

    def _generate_header(self, config: WorkflowConfig) -> str:
        """Generate workflow header."""
        return f"""# {config.name}
# Generated by ML CI/CD Toolkit on {datetime.now().strftime('%Y-%m-%d')}
# Workflow Type: {config.workflow_type.value}

name: {config.name}
"""

    def _generate_triggers(self, config: WorkflowConfig) -> str:
        """Generate trigger configuration."""
        lines = ["on:"]

        for trigger in config.triggers:
            if trigger == TriggerType.PUSH:
                lines.extend([
                    "  push:",
                    "    branches: [main, develop]",
                    "    paths:",
                    "      - 'src/**'",
                    "      - 'tests/**'",
                    "      - 'requirements.txt'",
                ])
            elif trigger == TriggerType.PULL_REQUEST:
                lines.extend([
                    "  pull_request:",
                    "    branches: [main]",
                ])
            elif trigger == TriggerType.SCHEDULE and config.schedule_cron:
                lines.extend([
                    "  schedule:",
                    f"    - cron: '{config.schedule_cron}'",
                ])
            elif trigger == TriggerType.WORKFLOW_DISPATCH:
                lines.extend([
                    "  workflow_dispatch:",
                    "    inputs:",
                    "      force_deploy:",
                    "        description: 'Force deployment'",
                    "        required: false",
                    "        default: 'false'",
                ])
            elif trigger == TriggerType.RELEASE:
                lines.extend([
                    "  release:",
                    "    types: [published]",
                ])

        return "\n".join(lines) + "\n"

    def _generate_env(self, config: WorkflowConfig) -> str:
        """Generate environment variables."""
        lines = [
            "env:",
            f"  PYTHON_VERSION: '{config.python_version}'",
            "  PIP_CACHE_DIR: ~/.cache/pip",
        ]

        if config.cache_models:
            lines.append("  MODEL_CACHE_DIR: ~/.cache/models")

        return "\n".join(lines) + "\n"

    def _generate_jobs(self, config: WorkflowConfig) -> str:
        """Generate jobs based on workflow type."""
        if config.workflow_type == WorkflowType.PR_VALIDATION:
            return self._generate_pr_validation_jobs(config)
        elif config.workflow_type == WorkflowType.CONTINUOUS_INTEGRATION:
            return self._generate_ci_jobs(config)
        elif config.workflow_type == WorkflowType.CONTINUOUS_TRAINING:
            return self._generate_ct_jobs(config)
        elif config.workflow_type == WorkflowType.MODEL_DEPLOYMENT:
            return self._generate_deployment_jobs(config)
        elif config.workflow_type == WorkflowType.DATA_VALIDATION:
            return self._generate_data_validation_jobs(config)
        else:
            return self._generate_full_pipeline_jobs(config)

    def _generate_pr_validation_jobs(self, config: WorkflowConfig) -> str:
        """Generate PR validation jobs."""
        jobs = ["jobs:"]

        # Lint job
        if config.run_lint:
            jobs.extend([
                "  lint:",
                f"    runs-on: {config.environment}",
                "    steps:",
                "      - uses: actions/checkout@v4",
                "      - uses: actions/setup-python@v5",
                "        with:",
                "          python-version: ${{ env.PYTHON_VERSION }}",
                "      - name: Install linters",
                "        run: pip install ruff black mypy",
                "      - name: Run ruff",
                "        run: ruff check src/",
                "      - name: Check formatting",
                "        run: black --check src/",
                "      - name: Type check",
                "        run: mypy src/ --ignore-missing-imports",
                "",
            ])

        # Test job
        if config.run_tests:
            jobs.extend([
                "  test:",
                f"    runs-on: {config.environment}",
            ])

            if config.run_lint:
                jobs.append("    needs: lint")

            jobs.extend([
                "    steps:",
                "      - uses: actions/checkout@v4",
                "      - uses: actions/setup-python@v5",
                "        with:",
                "          python-version: ${{ env.PYTHON_VERSION }}",
            ])

            if config.cache_pip:
                jobs.extend([
                    "      - uses: actions/cache@v4",
                    "        with:",
                    "          path: ${{ env.PIP_CACHE_DIR }}",
                    "          key: ${{ runner.os }}-pip-${{ hashFiles('requirements.txt') }}",
                ])

            jobs.extend([
                "      - name: Install dependencies",
                "        run: pip install -r requirements.txt pytest pytest-cov",
                "      - name: Run tests",
                "        run: pytest tests/ -v --cov=src --cov-report=xml",
                "      - name: Upload coverage",
                "        uses: codecov/codecov-action@v3",
                "        with:",
                "          files: coverage.xml",
                "",
            ])

        # Model smoke test
        if config.run_model_tests:
            jobs.extend([
                "  model-test:",
                f"    runs-on: {config.environment}",
                "    needs: test",
                "    steps:",
                "      - uses: actions/checkout@v4",
                "      - uses: actions/setup-python@v5",
                "        with:",
                "          python-version: ${{ env.PYTHON_VERSION }}",
                "      - name: Install dependencies",
                "        run: pip install -r requirements.txt",
                "      - name: Quick model test",
                "        run: python -m src.test_model --quick",
                "",
            ])

        return "\n".join(jobs)

