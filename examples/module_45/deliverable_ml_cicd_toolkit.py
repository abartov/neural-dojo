class ValidationGate:
    """Base class for validation gates."""

    def __init__(self, name: str, required: bool = True):
        self.name = name
        self.required = required

    def check(self, context: dict) -> GateResult:
        raise NotImplementedError


class AccuracyGate(ValidationGate):
    """Check if model accuracy meets threshold."""

    def __init__(self, threshold: float = 0.85, name: str = "accuracy"):
        super().__init__(name)
        self.threshold = threshold

    def check(self, context: dict) -> GateResult:
        accuracy = context.get('metrics', {}).get('accuracy', 0)

        if accuracy >= self.threshold:
            return GateResult(
                gate_name=self.name,
                status=GateStatus.PASSED,
                message=f"Accuracy {accuracy:.3f} >= {self.threshold:.3f}",
                value=accuracy,
                threshold=self.threshold,
            )
        else:
            return GateResult(
                gate_name=self.name,
                status=GateStatus.FAILED,
                message=f"Accuracy {accuracy:.3f} < {self.threshold:.3f}",
                value=accuracy,
                threshold=self.threshold,
            )


class LatencyGate(ValidationGate):
    """Check if inference latency is acceptable."""

    def __init__(self, max_ms: float = 100, name: str = "latency"):
        super().__init__(name)
        self.max_ms = max_ms

    def check(self, context: dict) -> GateResult:
        latency = context.get('metrics', {}).get('latency_p99_ms', float('inf'))

        if latency <= self.max_ms:
            return GateResult(
                gate_name=self.name,
                status=GateStatus.PASSED,
                message=f"Latency {latency:.1f}ms <= {self.max_ms:.1f}ms",
                value=latency,
                threshold=self.max_ms,
            )
        else:
            return GateResult(
                gate_name=self.name,
                status=GateStatus.FAILED,
                message=f"Latency {latency:.1f}ms > {self.max_ms:.1f}ms",
                value=latency,
                threshold=self.max_ms,
            )


class RegressionGate(ValidationGate):
    """Check that model doesn't regress from baseline."""

    def __init__(
        self,
        metric: str = "accuracy",
        tolerance: float = 0.01,
        name: str = "no_regression",
    ):
        super().__init__(name)
        self.metric = metric
        self.tolerance = tolerance

    def check(self, context: dict) -> GateResult:
        current = context.get('metrics', {}).get(self.metric, 0)
        baseline = context.get('baseline_metrics', {}).get(self.metric, 0)

        min_allowed = baseline * (1 - self.tolerance)

        if current >= min_allowed:
            return GateResult(
                gate_name=self.name,
                status=GateStatus.PASSED,
                message=f"No regression: {current:.3f} >= {min_allowed:.3f}",
                value=current,
                threshold=min_allowed,
                metadata={"baseline": baseline},
            )
        else:
            return GateResult(
                gate_name=self.name,
                status=GateStatus.FAILED,
                message=f"Regression: {current:.3f} < {min_allowed:.3f}",
                value=current,
                threshold=min_allowed,
                metadata={"baseline": baseline},
            )


class MemoryGate(ValidationGate):
    """Check if model memory usage is acceptable."""

    def __init__(self, max_mb: float = 1000, name: str = "memory"):
        super().__init__(name)
        self.max_mb = max_mb

    def check(self, context: dict) -> GateResult:
        memory = context.get('metrics', {}).get('memory_mb', 0)

        if memory <= self.max_mb:
            return GateResult(
                gate_name=self.name,
                status=GateStatus.PASSED,
                message=f"Memory {memory:.0f}MB <= {self.max_mb:.0f}MB",
                value=memory,
                threshold=self.max_mb,
            )
        else:
            return GateResult(
                gate_name=self.name,
                status=GateStatus.FAILED,
                message=f"Memory {memory:.0f}MB > {self.max_mb:.0f}MB",
                value=memory,
                threshold=self.max_mb,
            )


class DataQualityGate(ValidationGate):
    """Check data quality metrics."""

    def __init__(
        self,
        max_missing_ratio: float = 0.01,
        max_duplicate_ratio: float = 0.01,
        name: str = "data_quality",
    ):
        super().__init__(name)
        self.max_missing_ratio = max_missing_ratio
        self.max_duplicate_ratio = max_duplicate_ratio

    def check(self, context: dict) -> GateResult:
        data_metrics = context.get('data_metrics', {})
        missing_ratio = data_metrics.get('missing_ratio', 0)
        duplicate_ratio = data_metrics.get('duplicate_ratio', 0)

        issues = []
        if missing_ratio > self.max_missing_ratio:
            issues.append(f"missing={missing_ratio:.2%}")
        if duplicate_ratio > self.max_duplicate_ratio:
            issues.append(f"duplicates={duplicate_ratio:.2%}")

        if issues:
            return GateResult(
                gate_name=self.name,
                status=GateStatus.FAILED,
                message=f"Data quality issues: {', '.join(issues)}",
                metadata=data_metrics,
            )
        else:
            return GateResult(
                gate_name=self.name,
                status=GateStatus.PASSED,
                message="Data quality checks passed",
                metadata=data_metrics,
            )


class ValidationPipeline:
    """Run model through validation gates."""

    def __init__(self, gates: list = None):
        self.gates = gates or []

    def add_gate(self, gate: ValidationGate):
        """Add a gate to the pipeline."""
        self.gates.append(gate)

    def validate(self, context: dict) -> ValidationReport:
        """Run all gates and generate report."""
        results = []
        all_passed = True

        for gate in self.gates:
            result = gate.check(context)
            results.append(result)

            if result.status == GateStatus.FAILED and gate.required:
                all_passed = False

        overall_status = GateStatus.PASSED if all_passed else GateStatus.FAILED
        recommendation = "Deploy" if all_passed else "Do not deploy - fix failing gates"

        return ValidationReport(
            model_name=context.get('model_name', 'unknown'),
            timestamp=datetime.now().isoformat(),
            gates=[asdict(r) for r in results],
            overall_status=overall_status,
            recommendation=recommendation,
            metadata=context.get('metadata', {}),
        )


